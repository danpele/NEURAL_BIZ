// Lecture 8 game "Real or generated?": two series of 250 daily S&P 500 returns, one real, one from the GAN of the lecture.
// Data: L8_game_data.js (lectures/L8/make_game_L8.py). Engine: game_common.js. Charts: Plotly (loaded by the page).
(function () {
  'use strict';
  const G = window.NN_GAME_L8, I = G.info, { RO, nf, shuffle } = window.NNGame;
  const MON = RO ? ['ianuarie', 'februarie', 'martie', 'aprilie', 'mai', 'iunie', 'iulie', 'august', 'septembrie', 'octombrie', 'noiembrie', 'decembrie']
    : ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const date = s => { const [y, m, d] = s.split('-').map(Number); return `${d} ${MON[m - 1]} ${y}`; };
  const num = (x, d) => nf(x, d).replace('-', '−');
  const L = RO ? {
    ser: 'Seria', y: 'randament zilnic, %', x: 'ziua de tranzacționare',
    real: (a, b) => `Seria reală: S&amp;P 500, ${a} – ${b}`, gan: 'Cealaltă serie: 250 de zile consecutive generate de GAN',
    clus: (s, v) => `Gruparea volatilității (autocorelația medie a |randamentelor|, decalajele 1–${I.lags}), seria ${s}: <b>${num(v, 3)}</b>`,
    sd: (s, v) => `abaterea standard zilnică ${num(v, 2)} %`
  } : {
    ser: 'Series', y: 'daily return, %', x: 'trading day',
    real: (a, b) => `The real series: S&amp;P 500, ${a} – ${b}`, gan: 'The other series: 250 consecutive days generated by the GAN',
    clus: (s, v) => `Volatility clustering (mean autocorrelation of the |returns|, lags 1–${I.lags}), series ${s}: <b>${num(v, 3)}</b>`,
    sd: (s, v) => `daily standard deviation ${num(v, 2)}%`
  };
  const AB = ['A', 'B'];
  if (RO && window.Plotly) {   // Romanian number format on the axes (decimal comma)
    try { Plotly.register({ moduleType: 'locale', name: 'ro', dictionary: {}, format: { decimal: ',', thousands: '.' } }); } catch (e) { /* no locale */ }
  }
  const series = c => c.realFirst ? [c.real, c.fake] : [c.fake, c.real];
  const stat = c => c.realFirst ? [[c.c_real, c.sd_real], [c.c_fake, c.sd_fake]] : [[c.c_fake, c.sd_fake], [c.c_real, c.sd_real]];

  function draw(c) {
    if (!window.Plotly) return;
    const s = series(c), m = Math.max(...s.map(v => Math.max(...v.map(Math.abs)))), r = Math.ceil(m);
    const x = s[0].map((_, i) => i + 1);
    s.forEach((v, i) => {
      const el = document.getElementById('g8-' + i);
      if (!el) return;
      Plotly.newPlot(el, [{ x, y: v, type: 'scatter', mode: 'lines', line: { color: '#1F4E79', width: 1 }, hoverinfo: 'skip' }], {
        margin: { l: 44, r: 8, t: 6, b: 34 }, paper_bgcolor: 'rgba(0,0,0,0)', plot_bgcolor: 'rgba(0,0,0,0)', showlegend: false,
        font: { family: 'Inter, sans-serif', size: 11 },
        xaxis: { title: { text: L.x, standoff: 4 }, range: [1, x.length], zeroline: false, fixedrange: true },
        yaxis: { title: { text: L.y, standoff: 2 }, range: [-r - 0.4, r + 0.4], tickvals: [-r, 0, r], zeroline: true, zerolinecolor: '#999', fixedrange: true }
      }, { displayModeBar: false, staticPlot: true, responsive: true, locale: RO ? 'ro' : 'en' });
    });
  }

  window.NNGame.choice({
    game: 'l8',
    cardTitle: { en: 'Pair', ro: 'Perechea' },
    draw: () => shuffle(G.pool).slice(0, I.per_game).map(c => Object.assign({}, c, { realFirst: Math.random() < 0.5 })),
    render: () => AB.map((s, i) => `<h4>${L.ser} ${s}</h4><div class="g-chart" id="g8-${i}" style="height:180px"></div>`).join(''),
    after: draw,
    choices: [{ label: { en: 'A is real', ro: 'A este reală' } }, { label: { en: 'B is real', ro: 'B este reală' } }],
    truth: c => (c.realFirst ? 0 : 1),
    model: c => { const t = stat(c); return t[0][0] > t[1][0] ? 0 : 1; },
    modelName: { en: 'The volatility-clustering check', ro: 'Testul de grupare a volatilității' },
    reveal: c => {
      const t = stat(c);
      return `<li>${L.real(date(c.d0), date(c.d1))}.</li><li>${L.gan}.</li>` +
        AB.map((s, i) => `<li>${L.clus(s, t[i][0])}; ${L.sd(s, t[i][1])}</li>`).join('');
    }
  });
})();
