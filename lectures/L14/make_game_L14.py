"""
make_game_L14.py -- data of the Lecture 14 game "You or the model? Market stress from chart images"
(interactive/L14_game.html, L14_game_ro.html).

Section 4 of the lecture draws each window of 120 trading days of the S&P 500 as a two-panel image (price, drawdown) and
labels it "stress" when the 20-day volatility at its end exceeds its rolling 90th percentile of the previous three years.
The game shows the same images (cache/chart_imgs.npy, the exact 224 x 224 inputs of the models) for TEST windows only
(2019 onwards; the models were fitted on windows up to 2018) and asks two kinds of questions:
  * 7 regime cards: calm or stress at the end of the window? Model: logistic regression on the CLIP image embeddings
    (column clip_probe of results/chart_regime.csv), decision at its 0.5 threshold; the logistic regression on the
    numbers (column numeric) is shown for comparison.
  * 3 trend cards: did the index end the window higher or lower? Model: Qwen2-VL-2B zero-shot (column vlm_up), at 0.5.
Truth: columns stress and up of results/chart_regime.csv (written by analysis_L14.py). The AUCs and the trend accuracy
are recomputed from that file and checked against L14_numbers.json.

Pools, drawn at random from the 394 test windows with the seed of the course: 12 stress and 24 calm windows for the regime
cards, 15 other windows for the trend cards. Every game draws 3 stress and 4 calm regime cards (stress is over-represented:
8.4% of the test windows) and 3 trend cards.

Run:  python3 lectures/L14/make_game_L14.py   ->  interactive/L14_game_data.js, interactive/game_img/L14/*.png, the two pages
"""
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402
from PIL import Image  # noqa: E402
from sklearn.metrics import roc_auc_score  # noqa: E402

SEED = npl.seed_all()
ROOT = os.path.join(HERE, "..", "..")
OUT = os.path.join(ROOT, "interactive", "L14_game_data.js")
IMG = os.path.join(ROOT, "interactive", "game_img", "L14")
os.makedirs(IMG, exist_ok=True)
NUM = json.load(open(os.path.join(HERE, "L14_numbers.json"), encoding="utf-8"))

d = pd.read_csv(os.path.join(HERE, "results", "chart_regime.csv"))
IM = np.load(os.path.join(HERE, "cache", "chart_imgs.npy"), mmap_mode="r")
assert len(d) == len(IM) == NUM["charts_task"]["n"]
te = np.where(d.split.values == "test")[0]
t = d.iloc[te]
assert len(t) == NUM["charts_task"]["n_test"]
assert round(100 * t.stress.mean(), 1) == NUM["charts_task"]["base_test"]
for col, key in (("clip_zs", "clip_zs"), ("clip_probe", "clip_probe"), ("numeric", "numeric"), ("vlm_stress", "vlm_zs")):
    assert round(roc_auc_score(t.stress, t[col]), 3) == NUM["regime"][key]["auc"], col
up_hat = (t.vlm_up > 0.5).astype(int)
assert round(100 * (up_hat == t.up).mean(), 1) == NUM["vl"]["trend_acc"]


def at_half(col):   # decisions at the 0.5 threshold on all test windows: share of stress windows flagged, of calm windows flagged
    f = (t[col] > 0.5).astype(int)
    return {"acc": round(100 * float((f == t.stress).mean()), 1), "hit": round(100 * float(f[t.stress == 1].mean()), 1),
            "false": round(100 * float(f[t.stress == 0].mean()), 1)}


rng = np.random.default_rng(SEED)
s_pos = rng.choice(te[t.stress.values == 1], 12, replace=False)
c_pos = rng.choice(te[t.stress.values == 0], 24, replace=False)
u_pos = rng.choice(np.setdiff1d(te, np.r_[s_pos, c_pos]), 15, replace=False)
pool = []
for kind, rows in (("r", np.r_[s_pos, c_pos]), ("t", u_pos)):
    for i in rows:
        r = d.iloc[i]
        name = f"w{r.end}.png"
        Image.fromarray(np.asarray(IM[i])).quantize(colors=64, method=Image.Quantize.MEDIANCUT).save(os.path.join(IMG, name), optimize=True)
        c = {"kind": kind, "img": name, "end": r.end}
        if kind == "r":
            c.update({"stress": int(r.stress), "p_img": round(float(r.clip_probe), 3), "p_num": round(float(r.numeric), 3)})
        else:
            c.update({"up": int(r.up), "p_up": round(float(r.vlm_up), 3), "ret": round(float(np.expm1(r.ret120)), 4)})
        pool.append(c)

info = {"n_test": int(len(t)), "n_stress": int(t.stress.sum()), "base": NUM["charts_task"]["base_test"], "seed": SEED,
        "first_test": str(t.end.min()), "last": str(t.end.max()), "regime": NUM["regime"], "trend": NUM["vl"],
        "probe": at_half("clip_probe"), "numeric": at_half("numeric"),
        "pool_stress": len(s_pos), "pool_calm": len(c_pos), "pool_trend": len(u_pos), "stress_per_game": 3, "calm_per_game": 4, "trend_per_game": 3}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L14/make_game_L14.py -- do not edit\n")
    f.write("window.NN_GAME_L14 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False) + ";\n")
sizes = [os.path.getsize(os.path.join(IMG, p["img"])) for p in pool]
print(OUT, json.dumps(info), f"images: {len(sizes)}, max {max(sizes)} B, total {sum(sizes)} B")

