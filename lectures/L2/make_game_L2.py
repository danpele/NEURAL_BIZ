"""
make_game_L2.py -- data of the Lecture 2 game "Fast or slow training?" (interactive/L2_game.html, L2_game_ro.html).

The student sees a real training curve of the lecture and says which setting produced it:
  * the learning rate of plain stochastic gradient descent (SGD) on California housing (validation MSE, 30 epochs, seed 0;
    curves of lectures/L2/cache/interactive_v1.json, the runs behind the learning-rate sweep of analysis_L2.py);
  * the batch size of Adam on California housing (validation MSE, 40 epochs; cache/batch_v1.json);
  * the optimiser on card fraud (validation average precision, 30 epochs, 5 seeds each; cache/fraud_opt_v1.json).
No model answers: the game scores the student only. Nothing is retrained; the script checks that the cached runs give the
numbers of L2_numbers.json before writing.

Run:  python3 lectures/L2/make_game_L2.py      ->  interactive/L2_game_data.js, L2_game.html, L2_game_ro.html
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
OUT = os.path.join(HERE, "..", "..", "interactive", "L2_game_data.js")
C = os.path.join(HERE, "cache")
N = json.load(open(os.path.join(HERE, "L2_numbers.json")))
load = lambda name: json.load(open(os.path.join(C, name + ".json")))  # noqa: E731
r = lambda x, d=4: None if (x is None or not np.isfinite(x) or x >= 1e8) else round(float(x), d)  # noqa: E731

# ------------------------------------------------------------------ 1. learning rate (plain SGD, seed 0, 30 epochs)
LRS = ["0.0001", "0.003", "0.1", "0.3"]
inter, sweep = load("interactive_v1")["lr"], load("lr_sweep_v1")
lr_cards = []
for k in LRS:
    v = inter[k]
    assert abs(v[-1] - sweep[k][0]) < 1e-6, k            # same run as seed 0 of the sweep of analysis_L2.py
    lr_cards.append({"lr": float(k), "val": [r(x) for x in v]})
assert N["lrsweep"]["best_lr"] == 0.1 and N["lrsweep"]["first_diverged"] == 0.3

# ------------------------------------------------------------------ 2. batch size (Adam, lr 0.001, 40 epochs)
br = load("batch_v1")
bs_cards = []
for b in ("16", "128", "1024"):
    assert round(br[b]["val"][-1], 3) == N["batch"][b]["val_final"]
    bs_cards.append({"bs": int(b), "val": [r(x) for x in br[b]["val"]], "test": r(br[b]["test"]), "sec": round(br[b]["sec"], 1),
                     "spe": N["batch"][b]["steps_per_epoch"]})

# ------------------------------------------------------------------ 3. optimiser on card fraud (validation PR-AUC, 5 seeds)
fo = load("fraud_opt_v1")
FLR = {"sgd": 0.01, "momentum": 0.01, "adam": 0.001}      # fraud_all() of analysis_L2.py
op_cards = []
for o in ("sgd", "momentum", "adam"):
    assert round(float(np.mean([x["ap"][0] for x in fo[o]])), 3) == N["fraud"][o]["ap_ep1"]
    assert round(float(np.mean([x["ap_test"] for x in fo[o]])), 3) == N["fraud"][o]["ap_test"]
    for s, x in enumerate(fo[o]):
        op_cards.append({"opt": o, "seed": s, "lr": FLR[o], "ap": [r(a) for a in x["ap"]], "test": r(x["ap_test"])})

info = {"seed": N["seed"], "mse_lin_val": N["cal"]["mse_lin_val"], "n_train": N["cal"]["n_train"], "n_val": N["cal"]["n_val"],
        "fr_n_val": N["fraud"]["n_val"], "per_kind": 3}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L2/make_game_L2.py -- do not edit\n")
    f.write("window.NN_GAME_L2 = " + json.dumps({"info": info, "lr": lr_cards, "bs": bs_cards, "opt": op_cards}, ensure_ascii=False) + ";\n")
print(OUT, info, len(op_cards))

# ------------------------------------------------------------------ the two pages
from game_page import write_game  # noqa: E402

ls, bt, fr = N["lrsweep"], N["batch"], N["fraud"]
en_num = lambda x, d=3: f"{x:,.{d}f}"  # noqa: E731
ro_num = lambda x, d=3: f"{x:,.{d}f}".replace(",", " ").replace(".", ",").replace(" ", ".")  # noqa: E731

write_game(2, en=dict(
    title="Fast or slow training? A training-curve game",
    lead="Every chart in this game is a real training run of Lecture 2. You see how the error of the network evolves, epoch by epoch, "
         "and you say which setting produced the curve: the learning rate, the batch size or the optimiser. Nine charts, about three minutes.",
    how="The first six runs fit a multilayer perceptron (MLP 64-64) to the 20,640 Californian census block groups of the lecture; the chart shows "
        "the mean squared error (MSE) on 4,128 validation block groups the network does not train on (lower is better). The last three runs detect "
        "card fraud; the chart shows the area under the precision-recall curve (PR-AUC) on the validation transactions (higher is better). There is no model to beat here: "
        "only your score counts.",
    lesson=[f"<li>With plain stochastic gradient descent (SGD) and 30 epochs, the learning rate decides everything: η = 0.0001 leaves the validation MSE "
            f"at {en_num(ls['smallest_mse'])}, η = {ls['best_lr']:g} reaches {en_num(ls['best_mse'])}, and from η = {ls['first_diverged']:g} upwards training "
            "diverges (median of 3 seeds).</li>",
            f"<li>The optimiser sets the speed: after one epoch on card fraud the validation PR-AUC is {en_num(fr['sgd']['ap_ep1'])} with plain SGD, "
            f"{en_num(fr['momentum']['ap_ep1'])} with momentum and {en_num(fr['adam']['ap_ep1'])} with Adam; on the test transactions the three end at "
            f"{en_num(fr['sgd']['ap_test'])}, {en_num(fr['momentum']['ap_test'])} and {en_num(fr['adam']['ap_test'])} (5 seeds).</li>",
            f"<li>Small batches learn more per epoch (validation MSE after 5 epochs: {en_num(bt['16']['val_ep5'])} with batches of 16, "
            f"{en_num(bt['1024']['val_ep5'])} with 1,024) but cost more time: {bt['16']['sec']:.1f} s against {bt['1024']['sec']:.1f} s for 40 epochs.</li>"],
    src="Data: California housing, 1990 census (Pace and Barry, 1997; StatLib), split 60/20/20 at random; card fraud of the Université libre de "
        "Bruxelles (ULB) and Worldline, Open Machine Learning platform (OpenML) dataset 1597, split by time. Curves: the runs of analysis_L2.py (seed 20261108; cached in lectures/L2/cache). "
        "Code: lectures/L2/make_game_L2.py."),
  ro=dict(
    title="Antrenare rapidă sau lentă? Un joc cu curbe de antrenare",
    lead="Fiecare grafic din acest joc este o antrenare reală din cursul 2. Vedeți cum evoluează eroarea rețelei, epocă după epocă, "
         "și indicați ce setare a produs curba: rata de învățare, mărimea lotului sau optimizatorul. Nouă grafice, circa trei minute.",
    how="Primele șase antrenări potrivesc un perceptron multistrat (MLP 64-64) pe cele 20.640 de grupuri de locuințe din recensămîntul californian "
        "folosit în curs; graficul arată eroarea pătratică medie (MSE) pe 4.128 de grupuri de validare pe care rețeaua nu se antrenează (mai mic "
        "înseamnă mai bine). Ultimele trei antrenări detectează fraude cu carduri; graficul arată aria de sub curba precizie-sensibilitate (PR-AUC) pe tranzacțiile de validare "
        "(mai mare înseamnă mai bine). Aici nu există un model cu care să vă comparați: contează doar scorul dumneavoastră.",
    lesson=[f"<li>Cu coborîrea stohastică pe gradient (SGD) simplă și 30 de epoci, rata de învățare decide totul: cu η = 0,0001, MSE pe validare "
            f"rămîne la {ro_num(ls['smallest_mse'])}, cu η = {ro_num(ls['best_lr'], 1)} ajunge la {ro_num(ls['best_mse'])}, iar de la "
            f"η = {ro_num(ls['first_diverged'], 1)} în sus antrenarea diverge (mediana a 3 inițializări).</li>",
            f"<li>Optimizatorul stabilește viteza: după o epocă pe datele de fraudă, PR-AUC pe validare este {ro_num(fr['sgd']['ap_ep1'])} cu SGD "
            f"simplu, {ro_num(fr['momentum']['ap_ep1'])} cu moment și {ro_num(fr['adam']['ap_ep1'])} cu Adam; pe tranzacțiile de test cele trei ajung la "
            f"{ro_num(fr['sgd']['ap_test'])}, {ro_num(fr['momentum']['ap_test'])} și {ro_num(fr['adam']['ap_test'])} (5 inițializări).</li>",
            f"<li>Loturile mici învață mai mult pe epocă (MSE pe validare după 5 epoci: {ro_num(bt['16']['val_ep5'])} cu loturi de 16, "
            f"{ro_num(bt['1024']['val_ep5'])} cu loturi de 1.024), dar cer mai mult timp: {ro_num(bt['16']['sec'], 1)} s față de "
            f"{ro_num(bt['1024']['sec'], 1)} s pentru 40 de epoci.</li>"],
    src="Date: locuințele din California, recensămîntul din 1990 (Pace și Barry, 1997; StatLib), împărțite aleator 60/20/20; fraudele cu carduri "
        "ale Université libre de Bruxelles (ULB) și Worldline, setul 1597 al platformei Open Machine Learning (OpenML), împărțite cronologic. Curbe: antrenările din analysis_L2.py (sămînța 20261108; "
        "salvate în lectures/L2/cache). Cod: lectures/L2/make_game_L2.py."))
print("pages written")
