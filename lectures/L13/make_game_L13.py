"""
make_game_L13.py -- data of the Lecture 13 game "Higher or lower than today?" (interactive/L13_game.html, L13_game_ro.html).

The student sees the daily average Romanian day-ahead electricity price of the last three weeks and decides whether
tomorrow's daily average will be higher or lower than today's; then sees the forecast of Chronos-2 (the foundation model
of the lecture, used zero-shot) and of LEAR (Lasso-estimated autoregressive model), and the real price.
Nothing is recomputed: the forecasts are the cached hourly forecasts of analysis_L13.py (results/forecasts_hourly.csv,
test year 1 November 2025 to 31 October 2026, the 360 evaluation days); a daily average is the mean of the 24 hourly
values, as in the lecture. The MAE of every model recomputed from this file is checked against L13_numbers.json.
The three weeks before each day come from the same hourly prices (OPCOM via energy-charts.info, data/clean) on the CET
day grid of analysis_L13.py; their value on the test days is checked against the 'actual' column.
Cards: 40 evaluation days drawn at random with numpy default_rng(20261108) (seed of the course); every game draws 10.

Run:  python3 lectures/L13/make_game_L13.py      ->  interactive/L13_game_data.js and the two pages
"""
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L13_game_data.js")
NUMS = json.load(open(os.path.join(HERE, "L13_numbers.json"), encoding="utf-8"))
L5R = json.load(open(os.path.join(HERE, "..", "L5", "L5_numbers.json"), encoding="utf-8"))["ret"]   # Lecture 5 hit rates, for the contrast
HIST, POOL, PER_GAME = 21, 40, 10
MODELS = ["naive", "lear", "dnn", "nbeats", "chronos2", "chronos2_cov", "bolt", "timesfm", "ens"]

# ---------------------------------------------------------------- cached forecasts of the test year
F = pd.read_csv(os.path.join(HERE, "results", "forecasts_hourly.csv"), parse_dates=["date"])
for k in MODELS:
    assert round(float((F[k] - F.actual).abs().mean()), 2) == NUMS["acc"][k]["mae"], k
DM = F.groupby("date")[["actual"] + MODELS].mean()                     # daily averages (24 hours)
assert (F.groupby("date").size() == 24).all()

# ---------------------------------------------------------------- daily averages of all days (same CET grid as analysis_L13.py)
TEST_END = pd.Timestamp(NUMS["split"]["test_end"])
P = npl.prices_hourly()["RO"]
df = pd.DataFrame({"v": P.values, "d": P.index.tz_localize(None).normalize(), "h": P.index.hour}, index=P.index)
RO = df.groupby(["d", "h"])["v"].mean().unstack("h").reindex(columns=range(24)).loc[:TEST_END]
dly = RO.mean(axis=1)                                                  # NaN on days with a missing hour
assert np.allclose(dly.reindex(DM.index).values, DM.actual.values, atol=1e-9)

days = DM.index
prev = dly.reindex(days - pd.Timedelta(days=1)).values
assert not np.isnan(prev).any()
up = DM.actual.values > prev
hit = {k: round(100 * float(np.mean((DM[k].values > prev) == up)), 1) for k in MODELS}
wd = DM.actual.groupby(days.dayofweek).mean()
info = {"seed": SEED, "hist": HIST, "pool": POOL, "per_game": PER_GAME, "n_days": int(len(days)),
        "first": str(days.min().date()), "last": str(days.max().date()), "up_share": round(100 * float(up.mean()), 1),
        "hit": hit, "mae": {k: NUMS["acc"][k]["mae"] for k in MODELS},
        "mean_mon_fri": round(float(DM.actual[days.dayofweek < 5].mean()), 1),
        "mean_sat": round(float(wd[5]), 1), "mean_sun": round(float(wd[6]), 1)}

rng = np.random.default_rng(SEED)
pool = []
for i in np.sort(rng.choice(len(days), POOL, replace=False)):
    D = days[i]
    h = dly.loc[D - pd.Timedelta(days=HIST):D - pd.Timedelta(days=1)]
    assert len(h) == HIST
    pool.append({"d": str(D.date()), "h": [None if np.isnan(v) else round(float(v), 2) for v in h.values],
                 "a": round(float(DM.actual.iloc[i]), 2), "c": round(float(DM.chronos2.iloc[i]), 2), "l": round(float(DM.lear.iloc[i]), 2)})
    assert pool[-1]["h"][-1] is not None
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L13/make_game_L13.py -- do not edit\n")
    f.write("window.NN_GAME_L13 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False) + ";\n")
print(OUT, json.dumps(info))
print("higher in pool:", sum(c["a"] > c["h"][-1] for c in pool), "of", POOL)

# ---------------------------------------------------------------- the two pages (interactive/L13_game.html, L13_game_ro.html)
from game_page import write_game  # noqa: E402

I, H, M = info, info["hit"], info["mae"]


def ro(x, d=1):
    return f"{x:,.{d}f}".replace(",", "X").replace(".", ",").replace("X", ".")


cut = round(100 * (1 - M["chronos2"] / M["naive"]))
write_game(13, en=dict(
    title="Higher or lower than today?",
    lead="You are the trader of a Romanian electricity supplier. You see the daily average day-ahead price of the last three weeks on the Romanian market "
         "(OPCOM, Romanian electricity and gas market operator) and decide: will tomorrow's average price be higher or lower than today's? After each decision "
         "you see the forecast of the foundation model of Lecture 13 and the real price. All 10 days come from the test year of the lecture "
         "(1 November 2025 to 31 October 2026).",
    how="The model is Chronos-2, a time-series foundation model pre-trained by Amazon on many other series and used zero-shot: it was never trained on Romanian "
        "prices. It reads the last 2,048 hourly prices (about 85 days) and forecasts the 24 hours of tomorrow; the game averages them. For comparison you also see "
        "LEAR (an autoregressive model estimated with the LASSO, least absolute shrinkage and selection operator), the classical benchmark of electricity price forecasting, recalibrated every day on three years of data.",
    lesson=[f"<li>On all {I['n_days']} evaluation days of the test year Chronos-2 calls the direction right on {H['chronos2']:.1f}% of days, LEAR on {H['lear']:.1f}%; the price rose "
            f"on {I['up_share']:.1f}% of days. In Lecture 5 the LSTM (long short-term memory network) called the direction of daily returns right on only {L5R['SP500']['hit_lstm']:.1f}% of days (S&amp;P 500) and {L5R['TLV']['hit_lstm']:.1f}% (Banca Transilvania).</li>",
            f"<li>Electricity has a calendar that stock prices do not have: in the test year the average day cost {I['mean_mon_fri']:.1f} EUR/MWh from Monday to "
            f"Friday, {I['mean_sat']:.1f} on Saturday and {I['mean_sun']:.1f} on Sunday. A good part of the game is the weekly cycle, and the model learned it "
            "from the context alone.</li>",
            f"<li>The lecture measures more than the direction: the mean absolute error (MAE) of Chronos-2 over the 24 hours is {M['chronos2']:.2f} EUR/MWh, "
            f"against {M['lear']:.2f} for LEAR and {M['naive']:.2f} for the naive rule: about {cut}% less than the naive rule.</li>"],
    src="Data: Romanian day-ahead prices (OPCOM, via energy-charts.info), daily averages of the 24 hourly prices; forecasts: cached test-year forecasts of "
        "analysis_L13.py (lectures/L13/results/forecasts_hourly.csv). The 40 days of the game are drawn at random from the 360 evaluation days (seed 20261108); "
        "every game draws 10 of them. Code: lectures/L13/make_game_L13.py."),
  ro=dict(
    title="Mai scump sau mai ieftin decît azi?",
    lead="Sînteți traderul unui furnizor român de energie electrică. Vedeți prețul mediu zilnic din piața pentru ziua următoare din ultimele trei săptămîni "
         "(OPCOM, operatorul pieței de energie electrică și de gaze naturale din România) și decideți: prețul mediu de mîine va fi mai mare sau mai mic decît cel de azi? "
         "După fiecare decizie vedeți prognoza modelului fundație din cursul 13 și prețul real. Toate cele 10 zile provin din anul de test al cursului "
         "(1 noiembrie 2025 - 31 octombrie 2026).",
    how="Modelul este Chronos-2, un model fundație pentru serii de timp, preantrenat de Amazon pe multe alte serii și folosit fără reantrenare: nu a fost antrenat "
        "niciodată pe prețurile din România. Citește ultimele 2.048 de prețuri orare (circa 85 de zile) și prognozează cele 24 de ore de mîine; jocul face media lor. "
        "Pentru comparație vedeți și LEAR (model autoregresiv estimat cu LASSO, least absolute shrinkage and selection operator), reperul clasic în prognoza prețului energiei, "
        "recalibrat zilnic pe trei ani de date.",
    lesson=[f"<li>Pe toate cele {I['n_days']} de zile de evaluare din anul de test, Chronos-2 ghicește direcția în {ro(H['chronos2'])} % din zile, iar LEAR în {ro(H['lear'])} %; prețul "
            f"a crescut în {ro(I['up_share'])} % din zile. În cursul 5, LSTM-ul (rețea cu memorie lungă pe termen scurt, long short-term memory) ghicea direcția randamentelor zilnice în doar {ro(L5R['SP500']['hit_lstm'])} % din zile (S&amp;P 500) și {ro(L5R['TLV']['hit_lstm'])} % (Banca Transilvania).</li>",
            f"<li>Energia electrică are un calendar pe care prețurile acțiunilor nu îl au: în anul de test, o zi a costat în medie {ro(I['mean_mon_fri'])} EUR/MWh de luni pînă "
            f"vineri, {ro(I['mean_sat'])} sîmbăta și {ro(I['mean_sun'])} duminica. O bună parte din joc ține de ciclul săptămînal, pe care modelul l-a învățat numai din context.</li>",
            f"<li>Cursul măsoară mai mult decît direcția: eroarea absolută medie (MAE) a Chronos-2 pe cele 24 de ore este {ro(M['chronos2'], 2)} EUR/MWh, față de "
            f"{ro(M['lear'], 2)} pentru LEAR și {ro(M['naive'], 2)} pentru regula naivă: cu circa {cut} % mai puțin decît regula naivă.</li>"],
    src="Date: prețurile din piața pentru ziua următoare din România (OPCOM, prin energy-charts.info), medii zilnice ale celor 24 de prețuri orare; prognoze: prognozele "
        "pentru anul de test salvate de analysis_L13.py (lectures/L13/results/forecasts_hourly.csv). Cele 40 de zile din joc sînt extrase aleator dintre cele 360 de "
        "zile de evaluare (sămînța 20261108); fiecare joc extrage 10 dintre ele. Cod: lectures/L13/make_game_L13.py."),
  plotly=True)
print("pages written")
