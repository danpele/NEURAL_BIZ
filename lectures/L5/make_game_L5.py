"""
make_game_L5.py -- data of the Lecture 5 game "Up or down tomorrow?" (interactive/L5_game.html, L5_game_ro.html).

The student sees the last 60 trading days of the S&P 500 or of Banca Transilvania (TLV) and decides whether the next
trading day closes up or down; then sees the direction forecast by the LSTM of the lecture and what really happened.
Nothing is retrained: the forecasts are those of task B of analysis_L5.py (cache/ret.pkl: 5 LSTM networks, 16 hidden
units, 22-day window of returns, training up to 2016, validation 2017-2019, test from 2 January 2020). The game uses the
mean forecast of the five networks (up if > 0). The hit rates of the lecture (mean over the five networks) are recomputed
from the cache and checked against L5_numbers.json.
Prices: same series and filters as analysis_L5.py (S&P 500 adjusted close, Yahoo Finance, days with high > low;
TLV adjusted close, EODHD, from 2008, rows with an unchanged price dropped); the cached returns are checked against them.
Cards: 20 test days per series drawn at random with numpy default_rng(20261108) (seed of the course); every game draws
5 cards of each series.

Run:  python3 lectures/L5/make_game_L5.py      ->  interactive/L5_game_data.js and the two pages
"""
import json
import os
import pickle
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L5_game_data.js")
NUMS = json.load(open(os.path.join(HERE, "L5_numbers.json"), encoding="utf-8"))
RT = pickle.load(open(os.path.join(HERE, "cache", "ret.pkl"), "rb"))
HIST, PER_SERIES, PER_GAME = 60, 20, 10

# ---------------------------------------------------------------- prices, exactly as in analysis_L5.py
cols = {f: npl.markets(f, ["SP500"])["SP500"] for f in ["open", "high", "low", "close", "adjclose"]}
spx = pd.DataFrame(cols).dropna()
END = (spx.index.max() + pd.Timedelta(days=1)).to_period("M").to_timestamp() - pd.Timedelta(days=1)
spx = spx.loc[:END]
spx = spx[(spx.high > spx.low)]
tlv = npl.bvb("adjclose", ["TLV"])["TLV"].dropna().loc[:END]
tlv = tlv[tlv.index >= "2008-01-01"]
tlv = tlv[tlv.diff() != 0]
PRICE = {"SP500": spx.adjclose, "TLV": tlv}

rng = np.random.default_rng(SEED)
pool, info = [], {"seed": SEED, "hist": HIST, "per_series": PER_SERIES, "per_game": PER_GAME, "W": NUMS["ret"]["W"]}
for name in ("SP500", "TLV"):
    o, px = RT[name], PRICE[name]
    y, mte, td, P = o["y"], o["mte"], pd.DatetimeIndex(o["td"]), o["pred"]
    # the cached returns are the log returns of these prices
    pos = px.index.get_indexer(td)
    assert (pos > 0).all()
    r = 100 * np.log(px.values[pos] / px.values[pos - 1])
    assert np.allclose(r, y, atol=1e-3), name
    # the lecture's numbers, recomputed from the cache
    hit_seed = [float(np.mean(np.sign(p[mte]) == np.sign(y[mte]))) for p in P]
    ens = P.mean(0)
    n = NUMS["ret"][name]
    assert round(100 * float(np.mean(hit_seed)), 1) == n["hit_lstm"], name
    assert round(100 * float(np.mean(y[mte] > 0)), 1) == n["up_share"], name
    assert int(mte.sum()) == n["n_test"], name
    info[name] = {"n_test": n["n_test"], "hit_lstm": n["hit_lstm"], "up_share": n["up_share"], "r2_lstm": n["r2_lstm_mean"],
                  "hit_ens": round(100 * float(np.mean(np.sign(ens[mte]) == np.sign(y[mte]))), 1),
                  "ens_up": round(100 * float(np.mean(ens[mte] > 0)), 1),
                  "first": str(td[mte].min().date()), "last": str(td[mte].max().date())}
    cand = np.where(mte & (pos >= HIST))[0]
    for i in np.sort(rng.choice(cand, PER_SERIES, replace=False)):
        k = pos[i]
        seg = px.iloc[k - HIST:k + 1]                     # 60 known closes + the close of the day to forecast
        pool.append({"s": name, "d": [str(x.date()) for x in seg.index], "p": [round(float(v), 2) for v in seg.values],
                     "f": round(float(ens[i]), 3), "nup": int((P[:, i] > 0).sum()), "y": round(float(y[i]), 3)})
info["vol_lstm_vs_naive"] = NUMS["vol"]["lstm_vs_naive_pct"]
info["acf_abs1"] = NUMS["acf"]["a1"]
assert all(c["y"] != 0 for c in pool)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L5/make_game_L5.py -- do not edit\n")
    f.write("window.NN_GAME_L5 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False) + ";\n")
print(OUT, json.dumps(info))

