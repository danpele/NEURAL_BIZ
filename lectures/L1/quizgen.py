"""
quizgen.py -- small helper for the quiz banks of Lectures 2 and 3 (assets/quizzes/lk.js): numbers are read from Lk_numbers.json
and formatted in English or Romanian; each question has 4 options, `correct` = index 0-3 in the original order, and the
incorrect explanation never names an option letter (the site engine shuffles the options).
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


class Bank:
    def __init__(self, k, numbers_path, title):
        self.k, self.title = k, title
        self.N = json.load(open(numbers_path))
        self.QS = []

    def g(self, key):
        v = self.N
        for p in key.split("."):
            v = v[p]
        return v

    def f(self, key, spec, lang):
        v = self.g(key)
        if spec == "sci":
            m, e = f"{float(v):.1e}".split("e")
            return (m.replace(".", ",") if lang == "ro" else m) + f"×10^{int(e)}"
        s = format(v, spec)
        if lang == "ro":
            s = s.replace(",", " ").replace(".", ",")
        else:
            s = s.replace(",", " ") if "," in spec else s
        return "−" + s[1:] if s.startswith("-") else s

    def E(self, key, spec):
        return self.f(key, spec, "en")

    def R(self, key, spec):
        return self.f(key, spec, "ro")

    def q(self, correct, en, ro):
        keys = ("title", "text", "options", "correctExplanation", "incorrectExplanation")
        self.QS.append({"correct": correct, "en": dict(zip(keys, en)), "ro": dict(zip(keys, ro))})

    def write(self, src):
        for i, qq in enumerate(self.QS):
            assert 0 <= qq["correct"] <= 3, i
            for lang in ("en", "ro"):
                assert len(qq[lang]["options"]) == 4 and len(set(qq[lang]["options"])) == 4, (i, lang)
                bad = (" A)", " B)", " C)", " D)", "option A", "option B", "option C", "option D", "varianta A", "varianta B")
                assert not any(w in qq[lang]["incorrectExplanation"] for w in bad), (i, lang)
        out = os.path.join(ROOT, "assets", "quizzes", f"l{self.k}.js")
        body = json.dumps({"draw": 20, "questions": self.QS}, ensure_ascii=False, indent=1)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write("// ============================================================\n"
                     f"// Quiz bank for lecture id 'l{self.k}': {self.title} (EN + RO)\n"
                     f"// GENERATED by {src} from L{self.k}_numbers.json; do not edit by hand.\n"
                     "// correct = index (0-3) of the right option in the original order; incorrectExplanation never names a letter.\n"
                     "// ============================================================\n"
                     f"window.NN_DATA.quizzes['l{self.k}'] = {body};\n")
        print("wrote", os.path.relpath(out, ROOT), len(self.QS), "questions")
