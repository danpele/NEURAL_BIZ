"""
webgen.py -- writes lectures/Lk/web_en.md and web_ro.md (format of lectures/common/build_web_lecture.py) from a bilingual
page description with @{key|fmt} number placeholders filled from Lk_numbers.json, and the frame hashes read from the decks.
Used by make_web_L1.py, make_web_L2.py, make_web_L3.py. Numbers are never typed into the page text by hand.
"""
import json
import os
import re
import subprocess
import sys

COMMON = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common"))
sys.path.insert(0, COMMON)
import build_web_lecture as bwl  # noqa: E402

MON = {"en": ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
       "ro": ["ianuarie", "februarie", "martie", "aprilie", "mai", "iunie", "iulie", "august", "septembrie", "octombrie", "noiembrie", "decembrie"]}


def fmt(v, spec, lang):
    if spec == "date":
        s = str(v)
        return f"{int(s[8:10])} {MON[lang][int(s[5:7]) - 1]} {s[:4]}"
    if isinstance(v, str):
        return v
    if spec == "sci":
        m, e = f"{float(v):.1e}".split("e")
        m = m.replace(".", ",") if lang == "ro" else m
        return f"${m}\\times10^{{{int(e)}}}$"
    s = format(v, spec) if spec else str(v)
    if lang == "ro":
        s = s.replace(",", "\x00").replace(".", ",").replace("\x00", " ")
    if s.startswith("-"):
        s = "−" + s[1:]
    return s


def render(text, N, lang):
    def get(key):
        v = N
        for p in key.split("."):
            v = v[int(p)] if isinstance(v, list) else v[p]
        return v
    return re.sub(r"@\{([A-Za-z][A-Za-z0-9_.]*)(?:\|([^{}]*))?\}", lambda m: fmt(get(m.group(1)), (m.group(2) or "").strip() or None, lang), text)


def frame_hashes(k):
    en, ro = bwl.read_deck(k, "en"), bwl.read_deck(k, "ro")
    return [(f["title"], f["hash"], g["hash"], g["title"]) for f, g in zip(en["frames"], ro["frames"])]


def write_pages(k, here, page):
    """page = dict(intro=(en, ro) [paragraph list], goals=[(en, ro)], sections=[dict(title=(en, ro), intro=(en, ro),
    blocks=[dict(frame=<EN frame title prefix>, title=(en, ro) or None, text=(en, ro), chart=name or None, cap=(en, ro),
    practice=(en, ro) or None, after=(en, ro) or None)], end=(en, ro))])"""
    N = json.load(open(os.path.join(here, f"L{k}_numbers.json")))
    H = frame_hashes(k)
    for li, lang in enumerate(("en", "ro")):
        out = [f"<!--\nWeb version of Lecture {k} ({lang.upper()}). GENERATED by lectures/L{k}/make_web_L{k}.py (numbers from L{k}_numbers.json);\n"
               f"built into web/L{k}{'' if lang == 'en' else '_ro'}.html by lectures/common/build_web_lecture.py.\n-->\n", "## @intro\n"]
        for para in page["intro"]:
            out.append(para[li] + "\n")
        out.append("@goals")
        out += [f"- {g[li]}" for g in page["goals"]]
        out.append("")
        for sec in page["sections"]:
            out.append(f"# {sec['title'][li]}\n")
            out.append(sec["intro"][li] + "\n")
            for b in sec["blocks"]:
                hit = [h for h in H if h[0].startswith(b["frame"])]
                if not hit:
                    raise KeyError(f"frame not found in the deck: {b['frame']}")
                _, he, hr, tro = hit[0]
                title = b.get("title")
                if title is None:
                    title = (hit[0][0], tro)
                out.append(f"## {title[li]} {{h={he if lang == 'en' else hr}}}\n")
                for para in (b["text"][li] if isinstance(b["text"][li], list) else [b["text"][li]]):
                    out.append(para + "\n")
                if b.get("chart"):
                    out.append(f"@chart {b['chart']}\n{b['cap'][li]}\n")
                if b.get("after"):
                    out.append(b["after"][li] + "\n")
                if b.get("practice"):
                    out.append(f"@practice {b['practice'][li]}\n")
            out.append("## @end\n")
            out.append(sec["end"][li] + "\n")
        txt = render("\n".join(out), N, lang)
        with open(os.path.join(here, f"web_{lang}.md"), "w", encoding="utf-8") as fh:
            fh.write(txt)
    r = subprocess.run([sys.executable, os.path.join(COMMON, "build_web_lecture.py"), str(k)], capture_output=True, text=True)
    print(r.stdout[-3000:], r.stderr[-2000:])
    return r.returncode
