"""
make_game_L9.py -- data of the Lecture 9 game "Judge the transaction by its neighbours" (interactive/L9_game.html, L9_game_ro.html).

Each card shows one real labelled TEST transaction of the Elliptic Bitcoin graph (time steps 35-49, the test period of
the lecture) and its neighbourhood: its direct neighbours and their neighbours (two hops = the receptive field of the
two-layer graph networks of the lecture), each coloured by its label in the Elliptic data (illicit, licit, unknown); per neighbour at most
6 second-step neighbours are drawn (labelled ones first), the rest are counted.
The student decides illicit or licit; then the card shows the prediction of the lecture's GraphSAGE network (mean
probability of the three trained networks, seeds 1-3, threshold 0.5, as in results/test_scores.csv), of the same
network without the graph (multilayer perceptron, MLP) and the truth.

Everything comes from the cache of analysis_L9.py: cache/elliptic.npz (graph, labels, time steps) and cache/models.npz
(predicted probabilities). The script checks that the F1 scores of GraphSAGE and MLP equal L9_numbers.json.
Pool: test transactions with 1-12 direct neighbours and at least one labelled direct neighbour; 12 illicit and 18 licit
drawn at random (seed of the course), i.e. 40 % illicit against 6.5 % among all test transactions; every game draws
4 illicit and 6 licit.

Run:  python3 lectures/L9/make_game_L9.py      ->  interactive/L9_game_data.js, L9_game.html, L9_game_ro.html
"""
import json
import os
import sys

import numpy as np
from sklearn.metrics import f1_score

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L9_game_data.js")
NUM = json.load(open(os.path.join(HERE, "L9_numbers.json"), encoding="utf-8"))
N_ILL, N_LIC, PER_GAME, PER_ILL, MAX_DEG, MAX_R2 = 12, 18, 10, 4, 12, 6

z = np.load(os.path.join(HERE, "cache", "elliptic.npz"))
txid, step, cls, E = z["txid"], z["step"], z["cls"], z["E"]
P = np.load(os.path.join(HERE, "cache", "models.npz"), allow_pickle=True)["P"].item()
n = len(step)
test_m = (cls >= 0) & (step > 34)
y = cls[test_m]
for k in ("sage", "mlp", "gcn", "gat", "rf"):
    f1 = round(float(np.mean([f1_score(y, p[test_m] >= 0.5) for p in P[k]])), 3)
    assert f1 == NUM["models"][k]["f1"], (k, f1)
print("F1 equal L9_numbers.json")
p_sage, p_mlp = np.mean(P["sage"], 0), np.mean(P["mlp"], 0)

# undirected neighbour sets
Eu = np.concatenate([E, E[::-1]], axis=1)
o = np.argsort(Eu[0], kind="stable")
src, dst = Eu[0][o], Eu[1][o]
ptr = np.searchsorted(src, np.arange(n + 1))


def nb(v):
    return sorted(set(dst[ptr[v]:ptr[v + 1]].tolist()) - {v})


cand = {0: [], 1: []}
for v in np.where(test_m)[0]:
    ns = nb(v)
    if 1 <= len(ns) <= MAX_DEG and np.any(cls[ns] >= 0):
        cand[int(cls[v])].append(int(v))
rng = np.random.default_rng(SEED)
chosen = list(rng.choice(cand[1], N_ILL, replace=False)) + list(rng.choice(cand[0], N_LIC, replace=False))

pool = []
for v in chosen:
    ring1 = nb(v)
    r1 = []
    for u in ring1:
        far = [w for w in nb(u) if w != v and w not in ring1]
        lab = cls[far] if far else np.array([], dtype=int)
        r1.append({"l": int(cls[u]), "r2": [int((lab == 1).sum()), int((lab == 0).sum()), int((lab == -1).sum())]})
    two = sorted({w for u in ring1 for w in nb(u)} - set(ring1) - {v})     # distinct nodes two steps away
    d2 = [int((cls[two] == 1).sum()), int((cls[two] == 0).sum()), int((cls[two] == -1).sum())] if two else [0, 0, 0]
    pool.append({"id": int(txid[v]), "step": int(step[v]), "ill": int(cls[v]), "r1": r1, "d2": d2,
                 "sage": round(float(p_sage[v]), 3), "mlp": round(float(p_mlp[v]), 3)})

info = {"seed": SEED, "pool_ill": N_ILL, "pool_lic": N_LIC, "per_game": PER_GAME, "per_ill": PER_ILL, "max_deg": MAX_DEG, "max_r2": MAX_R2,
        "n_cand_ill": len(cand[1]), "n_cand_lic": len(cand[0]),
        "n_test": NUM["data"]["n_test"], "pct_test_illicit": NUM["data"]["pct_test_illicit"],
        "h_ill": NUM["homophily"]["illicit_nb_of_illicit_pct"], "h_lic": NUM["homophily"]["illicit_nb_of_licit_pct"],
        "f1_sage": NUM["models"]["sage"]["f1"], "f1_mlp": NUM["models"]["mlp"]["f1"], "f1_rf": NUM["models"]["rf"]["f1"],
        "pool_sage_hits": int(sum((c["sage"] >= 0.5) == bool(c["ill"]) for c in pool)),
        "pool_mlp_hits": int(sum((c["mlp"] >= 0.5) == bool(c["ill"]) for c in pool))}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L9/make_game_L9.py -- do not edit\n")
    f.write("window.NN_GAME_L9 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(OUT, info)

