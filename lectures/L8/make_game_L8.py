"""
make_game_L8.py -- data of the Lecture 8 game "Real or generated?" (interactive/L8_game.html, L8_game_ro.html).

Each card shows two series of 250 daily S&P 500 log returns (about one trading year): one is a real window of the
training period of the lecture (4 Jan 2005 - 31 Dec 2019), the other 250 consecutive samples of the lecture's GAN
(cache/gan.npz, generator of seed 1, rescaled with the training standard deviation exactly as in analysis_L8.py).
The student picks the real one.

The "model" is the stylised-fact check of the lecture (chart gan_acf): volatility clustering, measured as the mean
autocorrelation of the absolute returns at lags 1-5 (one trading week); the series with the larger value is called real.
Its hit rate on 1,000 random pairs (seed of the course) is printed on the end screen.

Data and GAN samples as in analysis_L8.py (same download, same end of sample, same standardisation); the script checks
that the kurtosis and the lag-1 autocorrelation equal kurt_real, kurt_gan, acf1_real, acf1_gan of L8_numbers.json.
Pool: 24 pairs, real windows drawn at random from the training period, GAN windows from disjoint blocks of the seed-1
samples (seed 20261108); every game draws 10 of them.

Run:  python3 lectures/L8/make_game_L8.py      ->  interactive/L8_game_data.js, L8_game.html, L8_game_ro.html
"""
import json
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L8_game_data.js")
NUM = json.load(open(os.path.join(HERE, "L8_numbers.json"), encoding="utf-8"))["gan"]
W, POOL, PER_GAME, LAGS = 250, 24, 10, 5

# ---------------------------------------------------------------- data exactly as in analysis_L8.py, part C
px = npl.markets("adjclose", ["SP500"])["SP500"].dropna()
end = (px.index.max() + pd.Timedelta(days=1)).to_period("M").to_timestamp() - pd.Timedelta(days=1)
px = px.loc[:end]
r = np.log(px).diff().dropna()
rtr = r.loc[:"2019-12-31"]
s_tr = float(rtr.std())
ztr = (rtr.values / s_tr).astype(np.float32)
GS = np.load(os.path.join(HERE, "cache", "gan.npz"), allow_pickle=True)["GS"]
g1 = GS[0]


def acf_abs(x, lags=20):
    a = np.abs(x) - np.abs(x).mean()
    return np.array([np.sum(a[l:] * a[:-l]) / np.sum(a * a) for l in range(1, lags + 1)])


# check against the numbers of the slides
chk = {"kurt_real": round(float(stats.kurtosis(ztr)), 2), "kurt_gan": round(float(np.mean([stats.kurtosis(g) for g in GS])), 2),
       "acf1_real": round(float(acf_abs(ztr)[0]), 2), "acf1_gan": round(float(acf_abs(g1[:len(ztr)])[0]), 2),
       "var_real_pct": round(100 * float(np.quantile(ztr, 0.01)) * s_tr, 2)}
for k, v in chk.items():
    assert abs(v - NUM[k]) < 1e-9, (k, v, NUM[k])
print("numbers equal L8_numbers.json:", chk)


def clus(x):
    return float(np.mean(acf_abs(x, LAGS)))


# ---------------------------------------------------------------- hit rate of the check on 1,000 random pairs
rng = np.random.default_rng(SEED)
hits = 0
for _ in range(1000):
    a = rng.integers(0, len(ztr) - W)
    b = rng.integers(len(ztr), len(g1) - W)          # GAN blocks after the first len(ztr) samples (not used for acf1_gan)
    hits += clus(ztr[a:a + W]) > clus(g1[b:b + W])
hit_pct = round(100 * hits / 1000, 1)

# ---------------------------------------------------------------- pool of cards
rng = np.random.default_rng(SEED + 1)
starts = np.sort(rng.choice(np.arange(0, len(ztr) - W), POOL, replace=False))
blocks = rng.choice(np.arange(len(ztr) // W + 1, len(g1) // W), POOL, replace=False)
dates = rtr.index
pool = []
for st, bk in zip(starts, blocks):
    real = ztr[st:st + W] * s_tr
    fake = g1[bk * W:(bk + 1) * W] * s_tr
    pool.append({"real": [round(100 * float(v), 3) for v in real], "fake": [round(100 * float(v), 3) for v in fake],
                 "d0": str(dates[st].date()), "d1": str(dates[st + W - 1].date()),
                 "c_real": round(clus(real), 3), "c_fake": round(clus(fake), 3),
                 "k_real": round(float(stats.kurtosis(real)), 2), "k_fake": round(float(stats.kurtosis(fake)), 2),
                 "sd_real": round(100 * float(np.std(real, ddof=1)), 2), "sd_fake": round(100 * float(np.std(fake, ddof=1)), 2)})
pool_hits = sum(c["c_real"] > c["c_fake"] for c in pool)
info = {"w": W, "lags": LAGS, "pool": POOL, "per_game": PER_GAME, "seed": SEED, "hit_pct": hit_pct, "pool_hits": int(pool_hits),
        "n_train": len(ztr), **{k: NUM[k] for k in ("kurt_real", "kurt_gan", "acf1_real", "acf1_gan", "acf20_real", "var_real_pct", "var_gan_pct")}}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L8/make_game_L8.py -- do not edit\n")
    f.write("window.NN_GAME_L8 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(OUT, info)

# ---------------------------------------------------------------- the two pages
from game_page import write_game  # noqa: E402


def ro(x, d):
    return f"{x:.{d}f}".replace(".", ",").replace("-", "−")


def en(x, d):
    return f"{x:.{d}f}".replace("-", "−")


I = info
write_game(8, plotly=True, en=dict(
    title="Real or generated? S&amp;P 500 returns",
    lead="Each card shows two series of 250 daily returns of the S&amp;P 500 stock index, about one trading year. One is real, from the years "
         "2005–2019; the other was produced by the generative adversarial network (GAN) of Lecture 8, trained on the same years. Pick the real one.",
    how=f"The model you play against is not a network but a statistical check from the lecture: volatility clustering. For each series it computes "
        f"the average autocorrelation of the absolute returns over lags 1 to {LAGS} (one trading week) and calls the series with the larger value real.",
    lesson=[f"<li>The GAN learned the distribution of a single day well: its 1% Value-at-Risk (VaR) is {en(I['var_gan_pct'], 2)}% against "
            f"{en(I['var_real_pct'], 2)}% for the real returns, and its tails are fat (excess kurtosis {en(I['kurt_gan'], 2)} against {en(I['kurt_real'], 2)}).</li>",
            f"<li>It did not learn the order of the days: the autocorrelation of the absolute returns at lag 1 is {en(I['acf1_real'], 2)} for the real "
            f"returns and {en(I['acf1_gan'], 2)} for the GAN. Real markets have calm and turbulent periods; the GAN scatters its large moves at random.</li>",
            f"<li>This one statistic picks the real series in {en(I['hit_pct'], 1)}% of 1,000 random pairs. A generator for stress tests must produce "
            "whole paths, not single days: this is why sequence models and diffusion models follow in the lecture.</li>"],
    src="Data: S&amp;P 500, daily adjusted closing prices (Yahoo Finance), log returns 4 January 2005 – 31 December 2019; GAN samples: "
        f"lectures/L8/cache/gan.npz (generator of seed 1). The {POOL} pairs of the game are drawn at random (seed {SEED}); every game shows "
        f"{PER_GAME} of them, in random order and position. Code: lectures/L8/make_game_L8.py."),
  ro=dict(
    title="Real sau generat? Randamentele S&amp;P 500",
    lead="Fiecare carte arată două serii de cîte 250 de randamente zilnice ale indicelui bursier S&amp;P 500, cam un an de tranzacționare. Una este reală, "
         "din anii 2005–2019; cealaltă a fost produsă de rețeaua generativă adversarială (GAN) din cursul 8, antrenată pe aceiași ani. Alegeți seria reală.",
    how=f"Modelul cu care jucați nu este o rețea, ci un test statistic din curs: gruparea volatilității. Pentru fiecare serie calculează autocorelația "
        f"medie a randamentelor în valoare absolută la decalajele 1–{LAGS} (o săptămînă de tranzacționare) și declară reală seria cu valoarea mai mare.",
    lesson=[f"<li>GAN-ul a învățat bine distribuția unei singure zile: valoarea sa la risc (VaR) de 1 % este {ro(I['var_gan_pct'], 2)} %, față de "
            f"{ro(I['var_real_pct'], 2)} % pentru randamentele reale, iar cozile sînt groase (excesul de aplatizare {ro(I['kurt_gan'], 2)}, față de {ro(I['kurt_real'], 2)}).</li>",
            f"<li>Nu a învățat ordinea zilelor: autocorelația randamentelor în valoare absolută la decalajul 1 este {ro(I['acf1_real'], 2)} pentru randamentele "
            f"reale și {ro(I['acf1_gan'], 2)} pentru GAN. Piețele reale au perioade calme și perioade agitate; GAN-ul își împrăștie la întîmplare mișcările mari.</li>",
            f"<li>Doar această statistică alege seria reală în {ro(I['hit_pct'], 1)} % din 1.000 de perechi aleatoare. Un generator pentru teste de stres "
            "trebuie să producă traiectorii întregi, nu zile izolate; de aceea cursul continuă cu modelele de secvențe și cu modelele de difuzie.</li>"],
    src="Date: S&amp;P 500, prețuri zilnice de închidere ajustate (Yahoo Finance), randamente logaritmice 4 ianuarie 2005 – 31 decembrie 2019; eșantioane GAN: "
        f"lectures/L8/cache/gan.npz (generatorul cu sămînța 1). Cele {POOL} de perechi din joc sînt extrase aleator (sămînța {SEED}); fiecare joc arată "
        f"{PER_GAME} dintre ele, în ordine și poziție aleatoare. Cod: lectures/L8/make_game_L8.py."))
print("pages written")
