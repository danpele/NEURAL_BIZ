            f"label say bearish. Attention lets every word take its meaning from the other words of the text.</li>",
            f"<li>On all {info['n_test']:,} test tweets fine-tuned FinBERT reaches a macro-F1 of {M['finbert_ft']['macro_f1']:.1f}%, "
