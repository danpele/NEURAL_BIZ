"""
make_game_L7.py -- data of the Lecture 7 game "You or FinBERT? Finance tweets on which the models disagree"
(interactive/L7_game.html, L7_game_ro.html).

The student labels real finance tweets of the lecture's TEST set (published validation split of the Twitter financial news
data set, 2,388 tweets) as bearish, neutral or bullish; then sees the label of FinBERT fine-tuned (as in the lecture), the
label of the two simple models and the true label. Nothing is retrained: the predictions are the cached outputs of
analysis_L7.py (cache/finbert.json: FinBERT fine-tuned, seed 1; cache/tiny.json: embedding bag, seed 1;
results/test_predictions.csv: TF-IDF + logistic regression, and the same first runs of the other models). The script checks
that they reproduce the macro-F1 of L7_numbers.json.

The cards are deliberately hard for the simple models: the disagreement set is every test tweet on which TF-IDF + logistic
regression and the embedding bag give the SAME label and FinBERT fine-tuned gives a DIFFERENT one. The pool of 30 cards is
drawn at random from this set (seed of the course); every game draws 10 cards from the pool.

Run:  python3 lectures/L7/make_game_L7.py      ->  interactive/L7_game_data.js
"""
import json
import os
import re
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402
from sklearn.metrics import f1_score  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L7_game_data.js")
NUM = json.load(open(os.path.join(HERE, "L7_numbers.json"), encoding="utf-8"))
BTN = {0: 0, 2: 1, 1: 2}          # label of analysis_L7.py (bearish 0, bullish 1, neutral 2) -> button (bearish, neutral, bullish)
N_POOL = 30

tw = npl.tweets_sentiment()
te = tw[tw.split == "valid"].reset_index(drop=True)
y = te.label.values
P = pd.read_csv(os.path.join(HERE, "results", "test_predictions.csv"))
FC = json.load(open(os.path.join(HERE, "cache", "finbert.json")))
TC = json.load(open(os.path.join(HERE, "cache", "tiny.json")))
ft, eb, tf = np.array(FC["ft_pred"][0]), np.array(TC["embbag"]["pred"][0]), P.tfidf.values

# checks: same test tweets, same predictions, same numbers as the slides
assert len(te) == NUM["data"]["n_test"] and (P.y.values == y).all()
assert (P.finbert_ft.values == ft).all() and (P.embbag.values == eb).all()
mf1 = lambda p: 100 * f1_score(y, p, average="macro")  # noqa: E731
assert round(float(np.mean([mf1(np.array(p)) for p in FC["ft_pred"]])), 1) == NUM["models"]["finbert_ft"]["macro_f1"]
assert round(float(np.mean([mf1(np.array(p)) for p in TC["embbag"]["pred"]])), 1) == NUM["models"]["embbag"]["macro_f1"]
assert round(mf1(tf), 1) == NUM["models"]["tfidf"]["macro_f1"]

dis = np.where((tf == eb) & (ft != tf))[0]
d_ft = float(np.mean(ft[dis] == y[dis]))
d_simple = float(np.mean(tf[dis] == y[dis]))
rng = np.random.default_rng(SEED)
pos = rng.choice(dis, N_POOL, replace=False)


def clean(s):
    """Links (https://t.co/...) are removed for display; the text is otherwise unchanged."""
    return re.sub(r"\s+", " ", re.sub(r"https?://\S+", "", s)).strip()


# a real example of the disagreement set for the end screen (both simple models bullish, FinBERT and the label bearish)
k_ex = int(te.index[te.text.str.startswith("Beckhams")][0])
assert k_ex in dis and tf[k_ex] == 1 and ft[k_ex] == 0 and y[k_ex] == 0
EX = clean(te.text[k_ex])
pool = [{"t": clean(te.text[k]), "y": BTN[int(y[k])], "m": BTN[int(ft[k])], "s": BTN[int(tf[k])]} for k in pos]
info = {"seed": SEED, "n_test": int(len(te)), "n_dis": int(len(dis)), "dis_ft_pct": round(100 * d_ft, 1),
        "dis_simple_pct": round(100 * d_simple, 1), "pool": N_POOL, "per_game": 10,
        "pool_ft_right": int(sum(c["m"] == c["y"] for c in pool)), "pool_simple_right": int(sum(c["s"] == c["y"] for c in pool))}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L7/make_game_L7.py -- do not edit\n")
    f.write("window.NN_GAME_L7 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False) + ";\n")
print(OUT, info)


