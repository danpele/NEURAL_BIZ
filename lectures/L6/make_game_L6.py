acc_eb, f1_eb = S[MODEL]["acc"], S[MODEL]["f1"]
acc_tf, f1_tf = S["tfidf_lr"]["acc"], S["tfidf_lr"]["f1"]
gain = NUM["sent"]["pb_w2v_gain"]
cm, cover = NUM["cm"], NUM["oov"]["pb_cover"]
ntr = info["n_train"]
