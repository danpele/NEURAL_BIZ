"""
make_game_L6.py -- data of the Lecture 6 game "You or the network? Sentiment of financial news" (interactive/L6_game.html,
L6_game_ro.html).

The student reads real sentences of the Financial PhraseBank (Malo et al., 2014) and labels them negative, neutral or
positive; then sees the label of the embedding-bag network of the lecture (word2vec start) and the label of the annotators.
Nothing is retrained: the predictions are the cached outputs of analysis_L6.py (cache/sentiment.pkl), first of the five
random 70/15/15 splits (seed of the course). The script checks that the cached predictions reproduce the accuracies of
L6_numbers.json. The pool of cards is drawn at random from the TEST sentences of that split only (12 negative, 12 positive,
16 neutral; seed of the course), among sentences in plain ASCII with at most 40 words (readable on a phone); every game
draws 10 cards from this pool (3 negative, 3 positive, 4 neutral).

Run:  python3 lectures/L6/make_game_L6.py      ->  interactive/L6_game_data.js
"""
import json
import os
import pickle
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "common"))
import nn_plot as npl  # noqa: E402

SEED = npl.seed_all()
OUT = os.path.join(HERE, "..", "..", "interactive", "L6_game_data.js")
NUM = json.load(open(os.path.join(HERE, "L6_numbers.json"), encoding="utf-8"))
LAB = ["negative", "neutral", "positive"]          # order of analysis_L6.py (labels 0, 1, 2)
MODEL = "embbag_w2v"                               # embedding bag, word2vec start (the network of the lecture)

pb = npl.phrasebank(50)
pb_y = pb.label.map({k: i for i, k in enumerate(LAB)}).values


def pb_split(seed):
    """Identical to pb_split of analysis_L6.py: stratified 70/15/15, RandomState(SEED + seed)."""
    rs = np.random.RandomState(SEED + seed)
    tr, va, te = [], [], []
    for c in range(3):
        ids = rs.permutation(np.where(pb_y == c)[0])
        n = len(ids)
        tr += list(ids[:int(0.7 * n)]); va += list(ids[int(0.7 * n):int(0.85 * n)]); te += list(ids[int(0.85 * n):])
    return np.array(tr), np.array(va), np.array(te)


with open(os.path.join(HERE, "cache", "sentiment.pkl"), "rb") as f:
    SE = pickle.load(f)

# check: cached predictions = numbers of the slides (mean accuracy over the 5 splits)
for k in (MODEL, "tfidf_lr"):
    acc = np.mean([float((r["preds"][k] == pb_y[r["te"]]).mean()) for r in SE["pb"]]) * 100
    assert round(acc, 2) == NUM["sent"]["pb"][k]["acc"], (k, acc, NUM["sent"]["pb"][k]["acc"])
r0 = SE["pb"][0]
tr0, _, te0 = pb_split(0)
assert (np.array(r0["te"]) == te0).all()
assert len(tr0) == NUM["curve"]["n_full"]
yte, pred = pb_y[te0], np.asarray(r0["preds"][MODEL])
acc0 = float((pred == yte).mean())

rng = np.random.default_rng(SEED)
ok = np.array([s.isascii() and len(s.split()) <= 40 for s in pb.sentence.values[te0]])
pos = []
for c, n in ((0, 12), (2, 12), (1, 16)):
    pos += list(rng.choice(np.where((yte == c) & ok)[0], n, replace=False))
pool = [{"s": pb.sentence.iloc[te0[k]], "y": int(yte[k]), "m": int(pred[k])} for k in pos]

S = NUM["sent"]["pb"]
info = {"seed": SEED, "n_test": int(len(te0)), "n_train": int(len(tr0)), "acc0": round(100 * acc0, 1),
        "pool": {"neg": 12, "pos": 12, "neu": 16}, "game": {"neg": 3, "pos": 3, "neu": 4}, "per_game": 10,
        "pool_acc": round(100 * float(np.mean([c["m"] == c["y"] for c in pool])), 1)}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// generated by lectures/L6/make_game_L6.py -- do not edit\n")
    f.write("window.NN_GAME_L6 = " + json.dumps({"info": info, "pool": pool}, ensure_ascii=False) + ";\n")
print(OUT, info)


# ------------------------------------------------------------------ the two pages (interactive/L6_game.html, L6_game_ro.html)
